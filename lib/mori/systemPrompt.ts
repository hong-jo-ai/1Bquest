export interface MoriMode {
  /** office: 평일 08-19시 사무실 모드 / quiet: 그 외 조용 모드 */
  mode: "office" | "quiet";
  /** KST 기준 현재 시각 문자열 */
  nowKst: string;
}

/** KST 기준 현재 모드/시각 산출. */
export function currentMode(now: Date = new Date()): MoriMode {
  const kst = new Date(now.getTime() + 9 * 60 * 60 * 1000);
  const day = kst.getUTCDay(); // 0=일 ... 6=토
  const hour = kst.getUTCHours();
  const isWeekday = day >= 1 && day <= 5;
  const isOfficeHours = hour >= 8 && hour < 19;
  const nowKst = kst.toISOString().replace("T", " ").slice(0, 16) + " (KST)";
  return { mode: isWeekday && isOfficeHours ? "office" : "quiet", nowKst };
}

