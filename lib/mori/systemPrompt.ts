/** 페르소나 + 현재 모드/시각을 합친 system 텍스트. */
export function buildSystemPrompt(m: MoriMode = currentMode()): string {
  const modeLine =
    m.mode === "office"
      ? "현재 모드: 사무실(office) — 업무시간. 능동적으로 거들어도 됩니다."
      : "현재 모드: 조용(quiet) — 업무시간 외/주말. 간결하게, 먼저 들이대지 않습니다.";
  return `${PERSONA}

# 지금
- 현재 시각: ${m.nowKst}
- ${modeLine}`;
}
